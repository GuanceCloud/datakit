// dateparse's upstream TestParse sets time.Local to UTC. Keep that oracle
// explicit here instead of inheriting the DataKit test process's local zone.
func normalizedDateparseTimestampVector(vector timestampTestVector) timestampTestVector {
	if vector.timezone == "" {
		vector.timezone = "Etc/UTC"
	}
	switch vector.value {
	case "Fri, 03 Jul 2015 08:08:08 PST":
		vector.timezone = "America/Los_Angeles"
	case "Tue, 11 Jul 2017 04:08:03 +0200 (CEST)":
		vector.timezone = "Europe/Berlin"
	case "Fri, 03-Jul-15 08:08:08 PST":
		vector.timezone = "America/Los_Angeles"
	case "Wednesday, 28-Feb-18 09:01:00 MST":
		vector.timezone = "America/Denver"
	case "2012-08-03 13:31:59 -0600 MST", "2012-08-03 13:31:59 MST", "2012-08-03 13:31:51 -07:00 MST":
		vector.timezone = "America/Denver"
	case "2015-02-08 03:02:00 +0200 CEST", "2015-02-08 03:02:00 +0200 CEST m=+0.000000001", "2012-08-03 13:31:51.123 +02:00 CEST":
		vector.timezone = "Europe/Berlin"
	case "2014-04-26 05:24:37 PST", "2012-08-03 18:31:59.000+00:00 PST", "2012-08-03 13:31:51.123 -08:00 PST":
		vector.timezone = "America/Los_Angeles"
	}
	return vector
}

